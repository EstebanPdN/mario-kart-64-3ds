def make_tile(name):
    rows = ART[name]
    assert len(rows) == 12 and all(len(row) == 12 for row in rows), name
    points = {(x, y): PALETTE[c] for y, row in enumerate(rows)
              for x, c in enumerate(row) if c != "."}
    x0, x1 = min(x for x, y in points), max(x for x, y in points)
    y0, y1 = min(y for x, y in points), max(y for x, y in points)
    width, height = x1 - x0 + 1, y1 - y0 + 1
    left, top = (18 - width) // 2, (18 - height) // 2
    pixels = []
    for y in range(18):
        for x in range(18):
            shade = 164 if y < 9 else 156
            if x == 0 or y == 0:
                shade = 230
            if x == 17 or y == 17:
                shade = 49
            pixels.append(0xff000000 | shade * 0x010101)
    for (x, y), shade in points.items():
        pixels[(top + y - y0) * 18 + left + x - x0] = 0xff000000 | shade * 0x010101
    return pixels, (left, top, width, height)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", type=Path)
    parser.add_argument("--check", action="store_true", help="Verify the generated header without writing it.")
    args = parser.parse_args()
    atlas = [0] * (128 * 128)
    bounds = []
    for index, name in enumerate(ART):
        pixels, box = make_tile(name)
        bounds.append(box)
        ox, oy = (index % 7) * 18, (index // 7) * 18
        for y in range(18):
            atlas[(oy + y) * 128 + ox:(oy + y) * 128 + ox + 18] = pixels[y * 18:y * 18 + 18]
    output = [
        "// Original pixel artwork; regenerate with assets/menu-hints/generate_icons.py.",
        "#pragma once", "#include <array>", "#include <cstdint>",
        "namespace mk64_3ds {", "enum class OptionIcon : uint8_t { " + ", ".join(ART) + " };",
        "namespace option_art {", "inline constexpr std::array<uint32_t,16384> kPixels = {",
    ]
    for start in range(0, len(atlas), 16):
        output.append("    " + ",".join(f"0x{pixel:08x}U" for pixel in atlas[start:start + 16]) + ",")
    output += ["};", "inline constexpr std::array<std::array<uint8_t,4>,25> kBounds = {{"]
    output += ["    {{" + ",".join(str(value) for value in box) + "}}," for box in bounds]
    output += ["}};", "} // namespace option_art", "} // namespace mk64_3ds"]
    target = Path(__file__).resolve().parents[2] / "source/art/option_icons_art_3ds.hpp"
    content="\n".join(output) + "\n"
    if args.check:
        if not target.exists() or target.read_text()!=content:
            parser.error("Generated option icons are stale; regenerate them.")
    elif not target.exists() or target.read_text()!=content:
        target.write_text(content)
    if args.preview:
        from PIL import Image
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        preview = Image.new("RGBA", (128, 128))
        preview.putdata([(p & 255, p >> 8 & 255, p >> 16 & 255, p >> 24) for p in atlas])
        preview.crop((0, 0, 126, 72)).resize((756, 432), Image.Resampling.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
