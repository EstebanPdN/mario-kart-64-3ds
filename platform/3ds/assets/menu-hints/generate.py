#!/usr/bin/env python3
"""Generate original native-resolution menu artwork; no game assets or fonts.

The checked-in RGBA header is the build input. PNG previews are optional private
outputs (--preview DIRECTORY). Python's standard library is sufficient to build.
"""
from pathlib import Path
import argparse

# Original compact pixel alphabet, stretched vertically without interpolation.
GLYPHS = {
    'A': ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
    'C': ['01111', '10000', '10000', '10000', '10000', '10000', '01111'],
    'D': ['11110', '10001', '10001', '10001', '10001', '10001', '11110'],
    'E': ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
    'I': ['111', '010', '010', '010', '010', '010', '111'],
    'L': ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
    'M': ['10001', '11011', '10101', '10101', '10001', '10001', '10001'],
    'N': ['10001', '11001', '11001', '10101', '10011', '10011', '10001'],
    'O': ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
    'P': ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
    'R': ['11110', '10001', '10001', '11110', '10100', '10010', '10001'],
    'S': ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
    'T': ['11111', '00100', '00100', '00100', '00100', '00100', '00100'],
    'U': ['10001', '10001', '10001', '10001', '10001', '10001', '01110'],
    ' ': ['000', '000', '000', '000', '000', '000', '000'],
}

def sprite(width, key, label):
    height=19
    pixels=[(0,0,0,255)]*(width*height)
    def put(x,y,c):
        if 0<=x<width and 0<=y<height: pixels[y*width+x]=(*c,255)
    def line(x0,y0,x1,y1,c):
        for y in range(y0,y1+1):
            for x in range(x0,x1+1): put(x,y,c)
    key_width=44 if key=='SELECT' else 16
    # Black is inside the texture, including under the label. The compact bevel
    # shares the reveal transform and opacity; there is no separate backing.
    for inset,light,dark in [(0,210,42),(1,245,90),(2,115,165)]:
        line(inset,inset,key_width-1-inset,inset,(light,)*3)
        line(inset,inset,inset,height-1-inset,(light,)*3)
        line(inset,height-1-inset,key_width-1-inset,height-1-inset,(dark,)*3)
        line(key_width-1-inset,inset,key_width-1-inset,height-1-inset,(dark,)*3)
    line(key_width,17,width-2,17,(95,95,108))
    line(width-2,2,width-2,17,(95,95,108))
    def text(word,left,right,colored):
        natural=sum(len(GLYPHS[c][0])+1 for c in word)-1
        available=right-left+1
        # Uniform integer sampling keeps letter shapes crisp at native size.
        target=min(natural,available)
        origin=left+(available-target)//2
        mask=[]
        for row in range(7): mask.append('0'.join(GLYPHS[c][row] for c in word))
        for y in range(12):
            for x in range(target):
                if mask[y*7//12][x*natural//target]=='1':
                    color=(255, max(0,255-(max(0,y-5)*255//6)), min(245,max(0,y-5)*245//6)) if colored else (245,245,245)
                    put(origin+x,3+y,color)
    text(key,4,key_width-5,False)
    text(label,key_width+2,width-4,True)
    return pixels

def generate():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--preview',type=Path)
    parser.add_argument('--check',action='store_true',help='Verify the generated header without writing it.')
    args=parser.parse_args()
    specs=[('Option',58,'L','OPTION'),('Data',58,'R','DATA'),
           ('RandomCup',127,'SELECT','RANDOM CUP'),('Auto',81,'SELECT','AUTO')]
    out=['// Generated by assets/menu-hints/generate.py. Do not edit.', '#pragma once',
         '#include <array>', '#include <cstdint>', 'namespace mk64_3ds::menu_art {']
    for name,width,key,label in specs:
        pixels=sprite(width,key,label)
        out.append(f'inline constexpr std::array<uint32_t, {width*19}> k{name} = {{')
        for start in range(0,len(pixels),12):
            out.append('    '+','.join(f'0x{a<<24|b<<16|g<<8|r:08x}U' for r,g,b,a in pixels[start:start+12])+',')
        out.append('};')
        if args.preview:
            from PIL import Image
            args.preview.mkdir(parents=True,exist_ok=True)
            im=Image.new('RGBA',(width,19)); im.putdata(pixels); im.save(args.preview/f'{name}.png')
    out.append('} // namespace mk64_3ds::menu_art')
    target=Path(__file__).resolve().parents[2]/'source/art/menu_art_3ds.hpp'
    content='\n'.join(out)+'\n'
    if args.check:
        if not target.exists() or target.read_text()!=content:parser.error('Generated menu hints are stale; regenerate them.')
    elif not target.exists() or target.read_text()!=content:target.write_text(content)

if __name__=='__main__': generate()
